/**
 * 원본 키를 보존한 적재 뒤 대상 시퀀스 재설정(DEC-OPS-306)을 실제 PostgreSQL 로 검증한다 — 온라인 앱의 다음
 * INSERT 가 이관한 키와 충돌하지 않는 것이 이 시험의 목적이다.
 */
@Testcontainers(disabledWithoutDocker = true)
class EtlSequenceResetPostgresIntegrationTest {

    @Container
    private static final PostgreSQLContainer POSTGRES = new PostgreSQLContainer("postgres:17-alpine");

    private static final AtomicInteger SEQUENCE = new AtomicInteger();
    private static final List<Long> SOURCE_KEYS = List.of(1L, 2L, 3L, 42L);

    private final EtlExecutor executor = new EtlExecutor(new SourceIntrospector(), new TransformerRegistry());

    @Test
    void preserveLoadAdvancesTheIdentitySoTheOnlineInsertDoesNotCollide() {
        Fixture fixture = fixture("identity");
        fixture.target().execute("CREATE TABLE " + fixture.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload varchar(20))");

        List<EtlExecutor.TableResult> first = executor.execute(fixture.preserve(Map.of()), MigrationMode.COMMIT);

        SequenceReset reset = singleReset(first);
        assertThat(reset.targetTable()).isEqualTo(fixture.table());
        assertThat(reset.column()).isEqualTo("id");
        assertThat(reset.sequence()).isEqualTo("public." + fixture.table() + "_id_seq");
        assertThat(reset.action()).isEqualTo(Action.ADVANCED);
        assertThat(onlineInsert(fixture)).as("온라인 앱의 다음 INSERT 는 이관한 최댓값 다음 키를 받는다").isEqualTo(43L);

        List<EtlExecutor.TableResult> rerun = executor.execute(fixture.preserve(Map.of()), MigrationMode.COMMIT);
        assertThat(singleReset(rerun).action()).as("다시 실행해도 시퀀스를 되돌리지 않는다").isEqualTo(Action.ALREADY_AHEAD);
        assertThat(onlineInsert(fixture)).isEqualTo(44L);
    }

    @Test
    void directColumnLoadsIntoSerialAndNextvalDefaultsAreAdvanced() {
        Fixture serial = fixture("serial");
        serial.target().execute("CREATE TABLE " + serial.table() + " (id bigserial PRIMARY KEY, payload varchar(20))");
        assertThat(singleReset(executor.execute(serial.direct(), MigrationMode.COMMIT)).action())
                .isEqualTo(Action.ADVANCED);
        assertThat(onlineInsert(serial)).isEqualTo(43L);

        Fixture standalone = fixture("standalone");
        String sequence = "sq_" + standalone.table();
        standalone.target().execute("CREATE SEQUENCE " + sequence);
        standalone.target().execute("CREATE TABLE " + standalone.table() + " (id bigint DEFAULT nextval('"
                + sequence + "') PRIMARY KEY, payload varchar(20))");
        SequenceReset reset = singleReset(executor.execute(standalone.direct(), MigrationMode.COMMIT));
        assertThat(reset.sequence()).isEqualTo("public." + sequence);
        assertThat(reset.action()).isEqualTo(Action.ADVANCED);
        assertThat(onlineInsert(standalone)).isEqualTo(43L);
    }

    @Test
    void entityOnlySequenceFailsClosedUntilTheMappingDeclaresIt() {
        Fixture fixture = fixture("entity_sequence");
        String sequence = "sq_" + fixture.table();
        fixture.target().execute("CREATE SEQUENCE " + sequence);
        fixture.target().execute("CREATE TABLE " + fixture.table() + " (id bigint PRIMARY KEY, payload varchar(20))");

        assertThatThrownBy(() -> executor.execute(fixture.preserve(Map.of()), MigrationMode.COMMIT))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining(fixture.table() + ".id: 원본 키를 보존하는 정수 키가 카탈로그로 연결된 시퀀스가 없어");
        assertThat(rows(fixture)).as("판정하지 못하면 행을 쓰기 전에 멈춘다").isZero();

        SequenceReset reset = singleReset(executor.execute(
                fixture.preserve(Map.of("id", sequence)), MigrationMode.COMMIT));
        assertThat(reset.sequence()).isEqualTo("public." + sequence);
        assertThat(reset.action()).isEqualTo(Action.ADVANCED);
        assertThat(fixture.target().queryForObject("SELECT nextval('" + sequence + "')", Long.class))
                .as("@SequenceGenerator 로 채번하는 온라인 앱의 다음 키").isEqualTo(43L);

        Fixture none = fixture("declared_none");
        none.target().execute("CREATE TABLE " + none.table() + " (id bigint PRIMARY KEY, payload varchar(20))");
        assertThat(singleReset(executor.execute(none.preserve(Map.of("id", "none")), MigrationMode.COMMIT)))
                .isEqualTo(new SequenceReset(none.table(), "id", null, Action.DECLARED_NONE));
    }

    @Test
    void undeterminableOrConflictingSequencesStopBeforeAnyRowIsWritten() {
        Fixture textDefault = fixture("text_default");
        String late = "sq_late_" + textDefault.table();
        textDefault.target().execute("CREATE SEQUENCE " + late);
        textDefault.target().execute("CREATE TABLE " + textDefault.table() + " (id bigint DEFAULT nextval('"
                + late + "'::text) PRIMARY KEY, payload varchar(20))");
        assertRejectedBeforeWriting(textDefault, textDefault.direct(), "기본값이 nextval 을 쓰지만 시퀀스를 판정할 수 없습니다");

        Fixture always = fixture("always");
        always.target().execute("CREATE TABLE " + always.table()
                + " (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, payload varchar(20))");
        assertRejectedBeforeWriting(always, always.preserve(Map.of()), "GENERATED ALWAYS identity 컬럼에는 원본 키를 쓸 수 없습니다");

        Fixture declaredNone = fixture("none_conflict");
        declaredNone.target().execute("CREATE TABLE " + declaredNone.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload varchar(20))");
        assertRejectedBeforeWriting(declaredNone, declaredNone.preserve(Map.of("id", "none")),
                "none 으로 선언했지만 카탈로그가 시퀀스");

        Fixture other = fixture("other_sequence");
        String unrelated = "sq_unrelated_" + other.table();
        other.target().execute("CREATE SEQUENCE " + unrelated);
        other.target().execute("CREATE TABLE " + other.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload varchar(20))");
        assertRejectedBeforeWriting(other, other.preserve(Map.of("id", unrelated)), "와 카탈로그가 연결한 시퀀스");

        Fixture missing = fixture("missing_sequence");
        missing.target().execute("CREATE TABLE " + missing.table() + " (id bigint PRIMARY KEY, payload varchar(20))");
        assertRejectedBeforeWriting(missing, missing.preserve(Map.of("id", "sq_missing_" + missing.table())),
                "선언한 시퀀스를 찾을 수 없습니다");

        Fixture ambiguous = fixture("ambiguous");
        String defaulted = "sq_default_" + ambiguous.table();
        String owned = "sq_owned_" + ambiguous.table();
        ambiguous.target().execute("CREATE SEQUENCE " + defaulted);
        ambiguous.target().execute("CREATE SEQUENCE " + owned);
        ambiguous.target().execute("CREATE TABLE " + ambiguous.table() + " (id bigint DEFAULT nextval('"
                + defaulted + "') PRIMARY KEY, payload varchar(20))");
        ambiguous.target().execute("ALTER SEQUENCE " + owned + " OWNED BY " + ambiguous.table() + ".id");
        assertRejectedBeforeWriting(ambiguous, ambiguous.direct(), "연결된 시퀀스가 둘 이상이라 하나로 정할 수 없습니다");
    }

    @Test
    void sequenceAlreadyAheadIsNotRewoundAndAnEmptyLoadIsRecorded() {
        Fixture ahead = fixture("ahead");
        ahead.target().execute("CREATE TABLE " + ahead.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload varchar(20))");
        ahead.target().queryForObject("SELECT setval(pg_get_serial_sequence('" + ahead.table() + "', 'id'), 1000)",
                Long.class);
        assertThat(singleReset(executor.execute(ahead.preserve(Map.of()), MigrationMode.COMMIT)).action())
                .isEqualTo(Action.ALREADY_AHEAD);
        assertThat(onlineInsert(ahead)).isEqualTo(1001L);

        Fixture empty = fixture("empty", List.of());
        empty.target().execute("CREATE TABLE " + empty.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload varchar(20))");
        assertThat(singleReset(executor.execute(empty.preserve(Map.of()), MigrationMode.COMMIT)).action())
                .isEqualTo(Action.EMPTY_TABLE);
        assertThat(onlineInsert(empty)).isEqualTo(1L);
    }

    @Test
    void aResetThatCannotHoldTheKeysFailsTheTableAndTheRun() {
        Fixture fixture = fixture("bounded");
        fixture.target().execute("CREATE TABLE " + fixture.table()
                + " (id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 10) PRIMARY KEY, payload varchar(20))");

        List<EtlExecutor.TableResult> results = executor.execute(fixture.preserve(Map.of()), MigrationMode.COMMIT);

        assertThat(results).singleElement().satisfies(result -> {
            assertThat(result.sequenceResets()).isEmpty();
            assertThat(result.errors()).containsExactly("시퀀스 재설정 실패(" + fixture.table()
                    + ".id): 원본 키 최댓값이 시퀀스 상한을 넘습니다");
            assertThat(String.join(" ", result.errors())).as("오류에도 키 값을 싣지 않는다").doesNotContain("42");
        });
        assertThat(fixture.target().queryForObject(
                "SELECT run_stts_cd FROM migration_control.tb_migration_run WHERE run_id=?",
                String.class, fixture.runId())).isEqualTo("FAILED");

        Fixture descending = fixture("descending");
        String sequence = "sq_desc_" + descending.table();
        descending.target().execute("CREATE SEQUENCE " + sequence + " INCREMENT BY -1");
        descending.target().execute("CREATE TABLE " + descending.table() + " (id bigint DEFAULT nextval('"
                + sequence + "') PRIMARY KEY, payload varchar(20))");
        assertThat(executor.execute(descending.direct(), MigrationMode.COMMIT)).singleElement()
                .satisfies(result -> assertThat(result.errors()).containsExactly("시퀀스 재설정 실패("
                        + descending.table() + ".id): 내림차순 시퀀스는 원본 키에 맞출 수 없습니다"));
    }

    private void assertRejectedBeforeWriting(Fixture fixture, MappingSpec spec, String message) {
        assertThatThrownBy(() -> executor.execute(spec, MigrationMode.COMMIT))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining(message);
        assertThat(rows(fixture)).isZero();
    }

    private static SequenceReset singleReset(List<EtlExecutor.TableResult> results) {
        assertThat(results).singleElement().satisfies(result -> assertThat(result.errors()).isEmpty());
        assertThat(results.getFirst().sequenceResets()).hasSize(1);
        return results.getFirst().sequenceResets().getFirst();
    }

    private static long onlineInsert(Fixture fixture) {
        return fixture.target().queryForObject(
                "INSERT INTO " + fixture.table() + " (payload) VALUES ('online') RETURNING id", Long.class);
    }

    private static long rows(Fixture fixture) {
        return fixture.target().queryForObject("SELECT count(*) FROM " + fixture.table(), Long.class);
    }

    private static Fixture fixture(String prefix) {
        return fixture(prefix, SOURCE_KEYS);
    }

    private static Fixture fixture(String prefix, List<Long> keys) {
        String suffix = prefix + "_" + SEQUENCE.incrementAndGet();
        DbConfig source = new DbConfig("jdbc:h2:mem:seq_" + suffix + ";DB_CLOSE_DELAY=-1", "sa", "", "org.h2.Driver");
        DbConfig target = new DbConfig(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword(), POSTGRES.getDriverClassName());
        JdbcTemplate sourceJdbc = jdbc(source);
        String sourceTable = "LEGACY_" + suffix.toUpperCase(java.util.Locale.ROOT);
        sourceJdbc.execute("CREATE TABLE " + sourceTable + " (ID bigint PRIMARY KEY, PAYLOAD varchar(20))");
        for (Long key : keys) {
            sourceJdbc.update("INSERT INTO " + sourceTable + " VALUES (?, 'legacy')", key);
        }
        return new Fixture(source, target, jdbc(target), sourceTable, "tb_seq_" + suffix,
                "run_" + UUID.randomUUID());
    }

    private static JdbcTemplate jdbc(DbConfig config) {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                config.url(), config.username(), config.password());
        dataSource.setDriverClassName(config.driver());
        return new JdbcTemplate(dataSource);
    }

    private record Fixture(DbConfig sourceConfig, DbConfig targetConfig, JdbcTemplate target,
                           String sourceTable, String table, String runId) {

        /** 원본 키를 typed preserve identity 로 보존한다. */
        MappingSpec preserve(Map<String, String> sequences) {
            return spec(new TableMapping(sourceTable, table, null, null, List.of("ID"), null,
                    List.of(new ColumnMapping("PAYLOAD", "payload", null, null, null, null, null)), null,
                    new IdentityStrategy(TargetIdentityPolicy.PRESERVE,
                            List.of(new IdentityComponentSpec("ID", IdentityValueType.SIGNED_INTEGER)),
                            List.of(new IdentityComponentSpec("id", IdentityValueType.SIGNED_INTEGER)),
                            sequences),
                    List.of()));
        }

        /** identity 선언 없이 원본 키를 직접 컬럼으로 옮긴다(기존 mapping 형태). */
        MappingSpec direct() {
            return spec(new TableMapping(sourceTable, table, null, null, List.of("ID"), "id",
                    List.of(new ColumnMapping("ID", "id", null, null, null, null, null),
                            new ColumnMapping("PAYLOAD", "payload", null, null, null, null, null)),
                    null, null, List.of()));
        }

        private MappingSpec spec(TableMapping mapping) {
            return new MappingSpec(sourceConfig, targetConfig, List.of(mapping), Map.of(),
                    new RunContext(runId, sourceConfig.url()));
        }
    }
}
