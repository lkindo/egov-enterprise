test('AI start is visible, discloses remote processing and requires an explicit checked consent', async t => {
  const dom = new JSDOM(markup, { url: 'http://127.0.0.1:8792/', runScripts: 'outside-only', pretendToBeVisual: true });
  t.after(() => dom.window.close());
  const { window } = dom, { document } = window;
  window.structuredClone = structuredClone;
  window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  const pack = createEmptyBacklogPack(context); pack.sources = [source]; pack.project = { code: 'SYNTHETIC', name: '합성 업무' };
  const state = { revision: 'synthetic-revision', backlog: pack, metadata: { baselines: [], exports: [], reviewedRequirements: {}, uatRecords: [], auditFindings: [] }, context, analysisReadiness: { valid: false, errors: [] }, readiness: { valid: false, errors: [] }, matches: { results: [] }, ai: { available: true, model: 'claude-opus-5-5', effort: 'xhigh', active: false, current: null, proposal: null, inputDigests: { analysis: 'synthetic-input' } } };
  const mutations = [];
  window.fetch = async (url, options = {}) => {
    if (url === '/api/action') mutations.push(JSON.parse(options.body));
    return { ok: true, json: async () => url === '/api/session' ? { token: 'synthetic-token' } : state };
  };
  await window.eval(`(async () => { ${script}\n })()`);
  const start = button(document, 'AI 요구사항 생성'); assert.ok(start, 'primary AI workflow must be discoverable');
  const files = button(document, 'AI로 산출물 등록'); assert.ok(files, 'AI upload is the primary workflow, without manual clause authoring');
  start.click();
  const consent = document.querySelector('#editor input[type="checkbox"]'); assert.ok(consent);
  const mode = document.querySelector('#editor select[name="visualMode"]'); assert.ok(mode);
  mode.value = 'text';
  assert.match(document.querySelector('#editor').textContent, /모델 서비스/);
  const submit = button(document, '동의하고 AI 분석 시작'); assert.ok(submit);
  submit.click(); await new Promise(resolve => setImmediate(resolve));
  assert.equal(mutations.length, 0, 'the unchecked form must not send registered sources');
  consent.checked = true; submit.click(); await new Promise(resolve => setImmediate(resolve));
  assert.equal(mutations.length, 1);
  assert.equal(mutations[0].action, 'ai.start');
  assert.equal(mutations[0].payload.consent, true);
  assert.equal(mutations[0].payload.inputDigest, 'synthetic-input');
  assert.equal(mutations[0].payload.includeVisuals, false);
  state.ai.current = { id: 'synthetic-job', phase: 'analysis', status: 'ready' };
  state.ai.proposal = { requirements: [], issues: [{ id: 'OBS', question: '확인할 참고 사항', severity: 'observation', options: [] }] };
  button(document, '최신 상태 읽기').click(); await new Promise(resolve => setImmediate(resolve));
  assert.ok(button(document, '답변하고 계속'), 'nonblocking questions can still receive a human answer');
  button(document, '요구사항 확정하고 에픽 생성').click();
  const continueAi = document.querySelector('[name="continue-ai"]'); assert.equal(continueAi.checked, true);
  continueAi.checked = false; continueAi.dispatchEvent(new window.Event('change', { bubbles: true }));
  document.querySelector('[name="ai-consent"]').checked = true;
  button(document, '요구사항만 확정').click(); await new Promise(resolve => setImmediate(resolve));
  assert.equal(mutations.at(-1).payload.continueWithAI, false);
  state.ai.current.phase = 'decomposition';
  state.ai.proposal = { workItems: [], acceptanceCriteria: [], issues: [{ id: 'PLAN', question: '작업 배치를 정해 주세요.', severity: 'blocking', options: [] }] };
  button(document, '최신 상태 읽기').click(); await new Promise(resolve => setImmediate(resolve));
  button(document, '답변하고 계속').click();
  document.querySelector('[name="answerScope"]').value = 'planning';
  document.querySelector('[name="answer-PLAN"]').value = '업무 요구사항을 유지하고 두 배치로 계획한다.';
  button(document, '답변을 반영하고 AI 계속 실행').click(); await new Promise(resolve => setImmediate(resolve));
  assert.equal(mutations.at(-1).payload.scope, 'planning');
});
