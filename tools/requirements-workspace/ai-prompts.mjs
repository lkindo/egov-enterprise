const visual = new Set(['pdf', 'png', 'jpg', 'jpeg', 'webp', 'tif', 'tiff', 'gif', 'bmp', 'hwp', 'hwpx']);
const tabular = new Set(['xlsx', 'xls', 'csv', 'tsv']);

export function buildStagePrompt(stage, { sourceTypes = [], formats = [], hasExisting = false, hasDecisions = false } = {}) {
  if (!Object.hasOwn(roles, stage)) throw Object.assign(new Error('AI_PROMPT_STAGE_INVALID'), { code: 'AI_PROMPT_STAGE_INVALID' });
  const parts = [`프롬프트 버전: ${PROMPT_VERSION} / 단계: ${stage}`, common, roles[stage]];
  for (const type of [...new Set(sourceTypes)]) if (Object.hasOwn(scenario, type)) parts.push(scenario[type]);
  if (formats.some(format => visual.has(format))) parts.push('시각 자료: 스캔·사진·수기·다단·도형은 읽기 순서와 연결 관계를 확인한다. 작은 글씨/기울어짐/흐림으로 판독하지 못한 부분은 위치와 불확실성을 남긴다. 이미지 해석은 원본 글자의 독립 검증을 뜻하지 않는다.');
  if (formats.some(format => tabular.has(format))) parts.push('표 자료: 시트/표 이름, 행·열 제목, 단위, 빈 셀과 병합 셀, 합계/상세, 표시값/수식의 구분을 보존한다. 빈 셀을 0이나 이전 값으로 채우지 않는다.');
  if (hasExisting) parts.push('재생성: 기존 사람 결정·식별자·문구·근거를 출발점으로 삼고 의미가 같은 항목을 다시 쓰지 않는다. 변경/제외는 명시하고 이전 검수 결과를 새 의미에 복사하지 않는다.');
  if (hasDecisions) parts.push('사용자 답변: 명시적으로 답한 질문의 범위에서만 결정을 반영한다. 새로 발견한 상충 조건은 숨기지 않고 별도 질문으로 남긴다.');
  return parts.join('\n\n');
}

export function promptManifest(features = {}) {
  return Object.keys(roles).map(stage => { const instructions = buildStagePrompt(stage, features); return { stage, version: PROMPT_VERSION, sha256: createHash('sha256').update(instructions).digest('hex'), instructions }; });
}
