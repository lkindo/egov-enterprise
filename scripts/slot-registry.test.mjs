test('a registry renders bound default imports in owner code point order, and an empty one has no side-effect import', () => {
  const text = renderSlotRegistry('recipient-picker-sources', ['note', 'addressbook']);
  assert.equal(text, [
    '// Generated by scripts/slot-registry.mjs from frontend/src/extensions/*/recipient-picker-sources.ts. Do not edit.',
    '// 다시 만들기: npm run slots:generate · 확인: npm run slots:check',
    "import type { SlotContributions } from './slots';",
    "import addressbook from './addressbook/recipient-picker-sources';",
    "import note from './note/recipient-picker-sources';",
    '',
    "export const recipientPickerSources: readonly SlotContributions<'recipient-picker-sources'>[] = [addressbook, note];",
    '',
  ].join('\n'));
  assert.equal(text.includes('\r'), false, 'the registry is rendered with LF');
  const empty = renderSlotRegistry('recipient-picker-sources', []);
  assert.deepEqual(empty.split('\n').filter(line => line.startsWith('import')), ["import type { SlotContributions } from './slots';"]);
  assert.match(empty, /= \[\];\n$/);
  assert.equal(slotExportName('shell-links'), 'shellLinks');
  // 바인딩이 될 수 없는 이름·중복·레지스트리 이름과 같은 기능 id·케밥이 아닌 슬롯은 렌더하지 않는다.
  assert.throws(() => renderSlotRegistry('recipient-picker-sources', ['delete']), /바인딩이 될 수 없는 기능 id: delete/);
  assert.throws(() => renderSlotRegistry('recipient-picker-sources', ['note', 'note']), /두 번 기여한다/);
  assert.throws(() => renderSlotRegistry('widgets', ['widgets']), /레지스트리 이름과 같다/);
  for (const slot of ['Recipient', 'recipient.sources', 'recipient_sources', 'generated-x']) assert.throws(() => renderSlotRegistry(slot, []), /케밥/);
});

test('slots are discovered from contribution file names and remaining registries; anything else in the slot root is refused', () => {
  const files = ['src/extensions/slots.ts', 'src/extensions/use-slot-entries.ts', 'frontend/src/extensions/note/shell-links.ts',
    'src/extensions/addressbook/shell-links.ts', 'src\\extensions\\generated-header-widgets.ts', 'src/app/page.tsx'];
  assert.deepEqual([...discoverSlotContributions(files)], [['header-widgets', []], ['shell-links', ['addressbook', 'note']]],
    'a registry without contributions keeps its slot (a generated product whose contributions were all projected away)');
  assert.deepEqual(slotPathKind('frontend/src/extensions/note/shell-links.ts'),
    { kind: 'contribution', owner: 'note', slot: 'shell-links', file: 'src/extensions/note/shell-links.ts' });
  assert.equal(slotPathKind('src/app/extensions/x.ts'), null);
  for (const stray of ['src/extensions/note/shell-links.tsx', 'src/extensions/note/nested/shell-links.ts', 'src/extensions/Note/shell-links.ts',
    'src/extensions/note/shell.links.ts', 'src/extensions/note/generated-x.ts', 'src/extensions/README.md', 'src/extensions/helpers.ts',
    'src/extensions/note/__tests__/x.test.ts']) {
    assert.throws(() => slotPathKind(stray), /슬롯 디렉터리에는/, stray);
  }
  assert.throws(() => frontendRelativePath('D:/project/frontend/src/extensions/slots.ts'), /절대 경로/);
  assert.throws(() => frontendRelativePath('/repo/frontend/src/extensions/slots.ts'), /절대 경로/);
});

test('drift is reported for a missing or hand-edited registry and ignores CRLF', t => {
  const root = mkdtempSync(join(tmpdir(), 'slot-registry-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const write = (file, text) => { mkdirSync(dirname(join(root, file)), { recursive: true }); writeFileSync(join(root, file), text); };
  write('src/extensions/slots.ts', 'export {};\n');
  write('src/extensions/note/shell-links.ts', 'export default [];\n');
  assert.deepEqual(slotRegistryDrift(root).map(row => [row.slot, row.reason]), [['shell-links', 'missing']]);
  write(slotRegistryPath('shell-links'), renderSlotRegistry('shell-links', ['note']).replace(/\n/g, '\r\n'));
  assert.deepEqual(slotRegistryDrift(root), [], 'a CRLF checkout of the rendered registry is not drift');
  write(slotRegistryPath('shell-links'), `${renderSlotRegistry('shell-links', ['note'])}import './note/shell-links';\n`);
  assert.deepEqual(slotRegistryDrift(root).map(row => [row.slot, row.reason]), [['shell-links', 'stale']], 'a side-effect import is drift');
});

const MANIFEST = {
  packs: { core: { rank: 0 }, demo: { rank: 1, frontend: { removePaths: ['src/extensions/note', 'src/app/note'] } } },
  profiles: { core: { packs: ['core'] }, demo: { packs: ['core', 'demo'] } },
};
const FILES = ['src/app/layout.tsx', 'src/app/note/page.tsx', 'src/extensions/slots.ts', 'src/extensions/note/shell-links.ts',
  'src/extensions/board/shell-links.ts', 'src/extensions/generated-shell-links.ts'];
const REGISTRY = slotRegistryPath('shell-links');

test('the projector re-renders a registry from the contributions its direct remove paths keep, in the same pass as markers', () => {
  const source = renderSlotRegistry('shell-links', ['board', 'note']);
  const core = createFrontendProjector({ manifest: MANIFEST, profile: MANIFEST.profiles.core, files: FILES });
  assert.equal(core.project(REGISTRY, source).source, renderSlotRegistry('shell-links', ['board']), 'the excluded contribution leaves the registry');
  assert.equal(core.project(`frontend/${REGISTRY}`, source).source, renderSlotRegistry('shell-links', ['board']), 'repository paths are the same file');
  // 구성 투영(생성기·정밀 점검)은 해석기가 계산한 제거 경로를 쓴다 — 두 번째 소유 판정은 없다.
  const custom = createFrontendProjector({ composition: { profile: 'custom', resolvedDomains: [], frontend: { removePaths: ['src/extensions/board/'] } },
    files: FILES.map(file => `frontend/${file}`) });
  assert.equal(custom.project(REGISTRY, source).source, renderSlotRegistry('shell-links', ['note']));
  // 원본 구성의 투영은 원문과 바이트가 같다 — CRLF 체크아웃도 그대로 돌려준다.
  const demo = createFrontendProjector({ manifest: MANIFEST, profile: MANIFEST.profiles.demo, files: FILES });
  const crlf = source.replace(/\n/g, '\r\n');
  assert.equal(demo.project(REGISTRY, crlf).source, crlf);
  // 손으로 고친 레지스트리는 원본 구성에서도 렌더 결과로 바뀐다(원본 parity 는 경계 계약이 따로 본다).
  assert.equal(demo.project(REGISTRY, `${source}export const extra = 1;\n`).source, source);
  // 파일 목록 없이 레지스트리를 투영하지 않는다 — 조용히 원문을 두면 지운 기여를 import 하는 레지스트리가 셸까지 연쇄로 지운다.
  assert.throws(() => createFrontendProjector({ manifest: MANIFEST, profile: MANIFEST.profiles.core }).project(REGISTRY, source),
    /복사할 프런트 파일 목록\(files\)이 필요하다/);
  // 레지스트리가 아닌 파일은 목록 없이도 투영한다.
  assert.equal(createFrontendProjector({ manifest: MANIFEST, profile: MANIFEST.profiles.core }).project('src/app/x.ts', 'x\n').source, 'x\n');
  // 슬롯 파일은 pack 마커를 둘 수 없다 — 기여는 파일 단위로 빠진다.
  const marked = '// reusable-base:demo:start\nexport const x = 1;\n// reusable-base:demo:end\nexport default [];\n';
  for (const file of ['src/extensions/board/shell-links.ts', REGISTRY, 'src/extensions/slots.ts']) {
    assert.throws(() => demo.project(file, marked), /슬롯 파일은 pack 마커를 둘 수 없다/, file);
  }
});

test('after the cascade the generator refuses a registry that no longer matches the surviving contributions', t => {
  const output = mkdtempSync(join(tmpdir(), 'slot-registry-prune-'));
  t.after(() => rmSync(output, { recursive: true, force: true }));
  const write = (file, text) => { mkdirSync(dirname(join(output, 'frontend', file)), { recursive: true }); writeFileSync(join(output, 'frontend', file), text); };
  write('src/app/layout.tsx', 'export default function Layout() { return null; }\n');
  write('src/app/note/page.tsx', 'export default function Page() { return null; }\n');
  write('src/extensions/slots.ts', 'export {};\n');
  write('src/extensions/note/shell-links.ts', 'export default [];\n');
  // board 기여가 지워지는 note 화면을 import 한다 — 직접 제거 경로에는 없지만 연쇄로 지워진다.
  write('src/extensions/board/shell-links.ts', "import '@/app/note/page';\nexport default [];\n");
  const files = FILES;
  const projector = createFrontendProjector({ manifest: MANIFEST, profile: MANIFEST.profiles.core, files });
  write(REGISTRY, projector.project(REGISTRY, renderSlotRegistry('shell-links', ['board', 'note'])).source);
  assert.throws(() => pruneFrontend(output, projector.directPaths),
    /투영 뒤 슬롯 레지스트리가 남은 기여와 다르다: src\/extensions\/generated-shell-links\.ts \(남은 기여: 없음\)/);
  // 대조군: 연쇄로 지워지지 않는 기여면 남은 기여와 레지스트리가 같고 lock 에 그대로 적힌다.
  const clean = mkdtempSync(join(tmpdir(), 'slot-registry-prune-'));
  t.after(() => rmSync(clean, { recursive: true, force: true }));
  const sources = { 'src/app/layout.tsx': 'export default function Layout() { return null; }\n', 'src/app/note/page.tsx': 'export default 1;\n',
    'src/extensions/slots.ts': 'export {};\n', 'src/extensions/note/shell-links.ts': 'export default [];\n',
    'src/extensions/board/shell-links.ts': 'export default [];\n', [REGISTRY]: renderSlotRegistry('shell-links', ['board']) };
  for (const [file, text] of Object.entries(sources)) {
    mkdirSync(dirname(join(clean, 'frontend', file)), { recursive: true });
    writeFileSync(join(clean, 'frontend', file), text);
  }
  assert.deepEqual(pruneFrontend(clean, projector.directPaths).slots, [{ slot: 'shell-links', owners: ['board'] }]);
});

// 배치를 가리지 못하는 슬롯은 소비자가 둘 이상인 평면 표다 — 허브별 표가 있거나 소비자가 하나면 오귀속이 없어 거부할 까닭이 없다.
test('every placement-blind slot is a flat consumer row with more than one consumer', () => {
  assert.ok(PLACEMENT_BLIND_SLOTS.length > 0);
  for (const slot of PLACEMENT_BLIND_SLOTS) {
    const row = SLOT_REGISTRY_CONSUMERS[slot];
    assert.ok(Array.isArray(row) && row.length > 1, `${slot} must list several consumers in one flat row`);
  }
});
