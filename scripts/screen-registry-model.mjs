/**
 * screen-registry-model — 화면 목록의 TypeScript 없는 부분(10단계 10b).
 *
 * 화면 목록 생성기(generate-screen-registry.mjs)는 쓰기·표시 권한을 귀속하려고 TypeScript AST(축 3)를 쓴다. 그 생성기는 적재할 때
 * 원본 frontend 의 TypeScript 를 읽으므로(operation-consumer-census.mjs → generated-boundary-census.mjs), 재사용 투영·정밀 점검·생성기
 * 화면이 정적으로 부르면 frontend 를 설치하지 않은 곳에서 적재부터 실패한다. 그래서 TypeScript 없이 정하는 부분을 이 모듈에 둔다:
 *   · 화면 목록의 뼈대(buildScreenFrame) — 화면 모집단·별칭·진입 권한·라벨·shellAccess.
 *   · 권한 묶음 원장의 검증과 여는 화면·관련 화면 계산(buildPermissionBundles), 화면 용어 원장의 금지 용어(replacedTermFinder).
 *   · 산출물의 렌더(renderScreenRegistry)·판독(readScreenRegistryArtifact)·불변식(validateScreenRegistry).
 * 생성기와 재사용 권한 투영(reusable-permission-projection.mjs)이 같은 함수를 쓴다 — 생성물에서 화면 목록을 데이터로 투영한 결과가
 * 생성물에서 다시 만든 결과와 화면·별칭·라벨·묶음 판정에서 갈리지 않는다. 이 모듈은 Node 내장 모듈과 TypeScript 를 읽지 않는 모듈만 쓴다.
 */
