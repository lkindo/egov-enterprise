-- ─────────────────────────────────────────────────────────────────────────────
-- [1] 1020300 '쪽지함' → '메일 발신 이력' 로 개명 (삭제하지 않음)
--
-- 실측: /admin/collaboration/mail-history 는 MailHistoryHubClient 이며 화면 제목이
--       "메일 발신 이력 관리", 부제가 "시스템에서 발송된 모든 메일 이력 및 전송 상태를 추적",
--       컬럼이 메일 제목·수신자·발송 일시·발송 상태다. 데이터는 mailService.getSentMails().
--       **쪽지함이 아니다.** 진짜 쪽지함은 1020400 '💌 업무 쪽지함' → /note 로 따로 있다.
--
-- 왜 삭제가 아니라 개명인가:
--   · 결함은 **중복이 아니라 이름**이다. 화면이 발신 이력인데 '쪽지함' 이라 부르는 것이 문제다.
--   · 메일 센터(1020000)의 동선이 성립한다 — 메일발송(1020200) → 발신 이력 확인.
--     이 항목을 지우면 방금 메일을 보낸 사용자가 이력을 보려고 '감사 및 통계' 로 가야 한다.
--   · 9040200 '발송메일내역'(감사 맥락)과 같은 화면을 가리키지만, **운영 동선과 감사 동선은
--     다른 맥락**이다. 같은 화면이 두 맥락에 나타나는 것 자체는 결함이 아니다.
--   · 삭제는 나중에도 할 수 있으나, 지운 메뉴를 되살리려면 tb_menu_crt_dtl 권한 매핑까지
--     다시 만들어야 한다. 되돌리기 쉬운 쪽을 먼저 택한다.
--
-- ⚠ 이로써 /admin/collaboration/mail-history 를 가리키는 활성 메뉴는 2건으로 남는다(의도적).
--   menu-census 는 이를 계속 '중복' 으로 표시하지만, 그것은 측정이지 판정이 아니다.
-- ─────────────────────────────────────────────────────────────────────────────

UPDATE tb_menu_info
   SET menu_nm = '메일 발신 이력', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1020300
   AND menu_nm = '쪽지함'
   AND modern_route = '/admin/collaboration/mail-history';

-- ─────────────────────────────────────────────────────────────────────────────
-- [2] 9040103 '접속통계' 삭제 (사용자 지시)
--
-- 실측: 9040102 '사용자통계' 와 **같은 화면**(/admin/stats/user)을 가리킨다.
--       '접속통계' 는 별개 기능이어야 하는데 대응 화면이 없어 사용자통계로 보내고 있었다 —
--       사용자는 다른 것을 기대하고 눌렀다가 같은 화면을 본다.
--       자식 메뉴 0건(실측)이라 트리가 끊기지 않는다.
--
-- 접속 통계 화면을 실제로 만들 때 이 메뉴를 새로 추가하면 된다.
-- ─────────────────────────────────────────────────────────────────────────────

DELETE FROM tb_menu_crt_dtl WHERE menu_sn = 9040103;
DELETE FROM tb_menu_info
 WHERE menu_sn = 9040103 AND menu_nm = '접속통계' AND modern_route = '/admin/stats/user';

-- ─────────────────────────────────────────────────────────────────────────────
-- [3] 9020110 '로그인' 삭제 (사용자 지시)
--
-- 실측: /admin/system/monitoring/hub?tab=security 를 가리키는데, 이름이 '로그인' 이라
--       무엇을 여는 메뉴인지 알 수 없다. 부모 9020100 '통합 보안 및 접속 정책' 과 같은 경로였고
--       (V2_46 에서 부모를 폴더화해 그 중복은 해소), 9040310 '보안 감사 로그' 도 같은 곳을 가리킨다.
--       레거시 잔재로 판단한다. 자식 메뉴 0건(실측).
--
-- 로그인 로그는 9040340 '상세 접속 로그 (Login)' → /admin/system/logs/login 이 따로 있어
-- 이 메뉴를 지워도 도달 경로가 사라지지 않는다(실측 확인).
-- ─────────────────────────────────────────────────────────────────────────────

DELETE FROM tb_menu_crt_dtl WHERE menu_sn = 9020110;
DELETE FROM tb_menu_info
 WHERE menu_sn = 9020110 AND menu_nm = '로그인';

-- ─────────────────────────────────────────────────────────────────────────────
-- [4] 9020120 '로그인정책관리' 경로 교정 — 이름이 맞는 화면으로 보낸다
--
-- ⚠ 이 항목은 "둘 중 어느 쪽이 정본인가" 가 아니었다. 실측하니 **셋이 서로 다른 기능**이다:
--
--   (가) /admin/security/login-policy        LoginPolicyAdminClient(387줄)
--        "로그인 보안 정책 — 개별 사용자의 접속 IP, 시간대 제한 및 2단계 인증(OTP)"
--        loginPolicyAdminService 를 쓰는 **유일한 화면**. → **이것이 로그인 정책이다.**
--        그런데 이 화면을 가리키는 메뉴가 **0건**이었다(실측). 즉 도달 불가.
--
--   (나) /admin/user/login-policy            UserOrgHubClient 의 'POLICIES'(조직 정책) 탭 진입점.
--        스텁이 아니다. 다만 그 탭은 /admin/user/indvdl-info-policy 로 이어지며
--        메뉴 9020130 '개인정보보호정책확인' 이 이미 그곳을 가리킨다 — 별개 기능이다.
--
--   (다) monitoring/hub?tab=policy           MonitoringHubClient 가 rawTab 'POLICY' 를
--        **'LOGIN' 탭으로 치환**한다(소스 실측). 즉 로그인 *로그* 화면이 열린다.
--        메뉴 9020120 '로그인정책관리' 가 여기를 가리켰다 — **이름이 거짓**이었다.
--
-- 조치: 9020120 을 (가)로 보낸다. 한 번의 변경으로 두 결함이 함께 해소된다 —
--       도달 불가였던 실기능이 연결되고, 거짓 이름이 사실이 된다.
--       로그인 로그는 9040340 이 이미 담당하므로 (다)로 가는 경로가 사라져도 손실이 없다.
-- ─────────────────────────────────────────────────────────────────────────────

UPDATE tb_menu_info
   SET modern_route = '/admin/security/login-policy', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 9020120
   AND modern_route = '/admin/system/monitoring/hub?tab=policy';

