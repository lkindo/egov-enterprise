-- 결재 양식·워크플로우 스튜디오 메뉴를 내린다 — 껍데기 화면을 가리키던 메뉴 정리.
--
-- [배경 · 원장 서술 정정]
-- 원장 D-3 은 "tb_sanctn_form + 컨트롤러 신설" 을 과제로 적었으나, 2026-08-06 실측 결과
--   · tb_sanctn_form 테이블은 **존재하지 않는다**(DB 86개 테이블 전수 확인)
--   · 결재 본체는 tb_ifml_atrz_info ↔ InformalSanction 으로 실재하고 **이미 배선돼 있다**
--     (ApprovalApiController + InformalSanctionApiController, FE ApprovalHubClient 가 실제 호출)
--   · 껍데기는 양식·스튜디오 3화면뿐이다:
--       /admin/sanctn/forms      (6줄 스텁, API 호출 0)
--       /admin/sanctn/workflow   (6줄 스텁, API 호출 0)
--       /admin/workflow          (166줄, API 호출 0 — 하드코딩 데모)
--
-- [왜 만들지 않고 내리는가]
-- tb_ifml_atrz_info 는 **0행**이다. 결재 자체가 아직 쓰이지 않는데 그 위에 양식 빌더를 얹는 것은
-- 순서가 거꾸로다. 양식 정의 + 결재선 규칙 + 조건 분기까지 가면 별도 제품 수준의 범위이고,
-- 실사용 사례 없이 설계하면 추측으로 스키마를 굳히게 된다.
-- 실제 운영에 올릴 계획이 잡히면 그때 사례를 근거로 설계하는 편이 낫다(2026-08-06 사용자 승인).
--
-- [⚠ 1050000 은 숨기지 않는다 — 숨기면 살아 있는 기능이 사라진다]
-- 1050000 '전자결재 및 문서 관리' 는 modern_route 가 스텁(/admin/sanctn/forms)을 가리키지만,
-- **실제 결재함 1050100 '내 결재함 및 대시보드'(/approvals)의 부모**다(실측).
-- use_yn='N' 으로 내리면 사이드바에서 자식까지 함께 사라져 완제품인 결재함이 도달 불가가 된다.
-- 대신 modern_route 를 비워 **순수 폴더**로 만든다 — 활성 메뉴 77건 중 6건이 이미 빈 route 로
-- 폴더 역할을 하고 있어(실측) 새로운 관례가 아니다.
--
-- [숨기는 것 — 둘 다 자식 0건이라 트리가 끊기지 않는다(실측)]
--   9030200 '결재 양식 관리'          → /admin/sanctn/forms (스텁)
--   9010500 '워크플로우 프로세스 설정' → /admin/workflow      (하드코딩 데모)
--
-- [삭제하지 않는 이유] tb_menu_crt_dtl(menu_sn, authrt_cd) 이 menu_sn 을 PK 로 참조한다
-- (V2_12 FK). use_yn='N' 은 사이드바에서만 감추고 권한 매핑을 보존한다 —
-- V2_27/V2_28/V2_30 이 이미 채택한 방식이며, 되살릴 때 그대로 재사용된다.
--
-- [화면 파일은 건드리지 않는다] 라우트 물리 삭제는 문자열 URL 참조를 정적 분석으로 잡을 수 없어
-- 과거 13개 오삭제 전례가 있다(V2_30). 메뉴에서 내리는 것으로 노출만 끝낸다.
--
-- [멱등성] 대상 menu_sn 과 현재 값 조건을 함께 걸어 재적용 시 0 rows 로 통과한다.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1) 1050000 을 순수 폴더로 — 스텁을 가리키던 route 를 비운다. 자식(결재함)은 그대로 노출된다.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tb_menu_info
   SET modern_route = NULL, mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1050000
   AND modern_route = '/admin/sanctn/forms';

-- ─────────────────────────────────────────────────────────────────────────────
-- 2) 껍데기 화면을 가리키던 잎 메뉴 2건 비활성화.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tb_menu_info
   SET use_yn = 'N', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn IN (
         9030200,  -- 결재 양식 관리          → /admin/sanctn/forms (스텁)
         9010500   -- 워크플로우 프로세스 설정 → /admin/workflow      (하드코딩 데모)
       )
   AND use_yn = 'Y';
