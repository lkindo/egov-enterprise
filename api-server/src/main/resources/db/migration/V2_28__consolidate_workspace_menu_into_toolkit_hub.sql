-- 워크스페이스의 중복 진입점을 '스마트 툴킷 허브' 한 갈래로 통합한다.
--
-- [배경]
-- 같은 세 기능이 두 갈래로 존재했다.
--
--   [워크스페이스 직속]                          [스마트 툴킷 허브(1060000) 하위]
--   1010000 업무 워크플로우 → work-hub?tab=job    1060100 부서 업무 관리 도구 → /smart-toolkit/dept-job
--   1010200 일정 캘린더     → work-hub?tab=calendar 1060200 통합 일정 도구     → /smart-toolkit/schedule
--   1040000 업무 보고       → work-hub?tab=report  1060300 업무 보고 관리 도구 → /smart-toolkit/work-report
--
-- 두 갈래는 "서로 다른 구현" 이 아니다. 네 라우트(위 셋 + /admin/work-hub)의 page.tsx 는 모두
-- 같은 WorkHubClient 를 감싼 6줄 래퍼이며, 정본이라 여겼던 /admin/work-hub 조차 동급 형제다.
-- 즉 중복은 구현 중복이 아니라 **메뉴 진입점 중복**이었다.
--
-- [왜 허브 쪽을 남기는가]
-- 직속 세 개는 같은 경로(/admin/work-hub)에 쿼리(?tab=)만 달랐다. 사이드바의 활성 표시가 쿼리
-- 일치에 의존하는 취약한 구조였고, 실제로 "다른 메뉴를 눌렀는데 엉뚱한 메뉴가 활성" 증상의
-- 근본 원인이었다(V2_25/V2_27 이 그 증상을 쫓아 두 번 손댔다). 허브 쪽은 세 기능이 각자 고유
-- 경로를 가지므로 쿼리 의존이 사라지고 북마크·딥링크도 자연스럽다.
-- 동반 코드 변경: WorkHubClient.setTab 이 '/admin/work-hub?tab=' 하드코딩 대신 탭별 실제 경로로
-- 이동하도록 수정됐다(그 하드코딩 탓에 허브 경로로 들어오면 탭 클릭 한 번에 튕겨나갔다).
--
-- [삭제하지 않는 이유]
-- tb_menu_crt_dtl(menu_sn, authrt_cd) 이 menu_sn 을 PK 로 참조한다(V2_12 FK). 물리 삭제하면 권한
-- 매핑까지 정리해야 하고 되돌리기 어렵다. use_yn='N' 은 사이드바에서만 감춰지고 언제든 복구된다.
-- V2_27 이 같은 이유로 이미 채택한 방식이다.
--
-- [멱등성] 모든 문장이 대상 menu_sn 과 현재 값 조건을 함께 걸어 재적용 시 0 rows 로 통과한다.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1) 【선행·필수】 1060300 의 권한 매핑 신설
--
-- MenuService.buildMenuTree 의 필터는 (isAuthorized || isAdmin) 이다. 1060300 은 권한 행이
-- 하나도 없어서 지금까지 **관리자에게만** 보였다(admin 우회 조항 덕분). 이 상태로 아래 3)에서
-- 1040000(업무 보고, ROLE_USER 보유)을 끄면 **일반 사용자는 업무 보고 메뉴를 통째로 잃는다.**
-- 형제(1060100/1060200)와 동일하게 채운다.
-- ─────────────────────────────────────────────────────────────────────────────
INSERT INTO tb_menu_crt_dtl (menu_sn, authrt_cd, mapng_crt_id, crt_dt, mdfcn_dt)
SELECT 1060300, v.authrt_cd, 'webmaster', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
  FROM (VALUES ('ROLE_ADMIN'), ('ROLE_USER')) AS v(authrt_cd)
 WHERE NOT EXISTS (
       SELECT 1 FROM tb_menu_crt_dtl d
        WHERE d.menu_sn = 1060300 AND d.authrt_cd = v.authrt_cd);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2) 허브 하위 세 메뉴의 이름을 화면의 탭 라벨과 일치시킨다.
--    '도구' 접미는 화면 어디에도 나타나지 않아 메뉴와 화면의 어휘가 어긋나 있었다.
--    (탭 라벨: 워크플로우 / 업무 보고 / 일정 — WorkHubClient.tsx)
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tb_menu_info SET menu_nm = '업무 워크플로우', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1060100 AND menu_nm = '부서 업무 관리 도구';

UPDATE tb_menu_info SET menu_nm = '일정 캘린더', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1060200 AND menu_nm = '통합 일정 도구';

UPDATE tb_menu_info SET menu_nm = '업무 보고', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1060300 AND menu_nm = '업무 보고 관리 도구';

-- ─────────────────────────────────────────────────────────────────────────────
-- 3) 워크스페이스 직속 중복 세 개를 비활성화한다.
--    1040000 의 자식 1040100/1040200 은 V2_27 에서 이미 use_yn='N' 이다.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tb_menu_info SET use_yn = 'N', mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn IN (1010000, 1010200, 1040000)
   AND use_yn = 'Y';

-- ─────────────────────────────────────────────────────────────────────────────
-- 4) menu_ordr 충돌 해소 — 1060300 과 1000001(통합 검색)이 둘 다 19 였다.
--    정렬 키가 같으면 순서가 비결정적이 되어 새로고침마다 메뉴 순서가 뒤바뀔 수 있다.
--    허브 하위는 17/18/19 로 연속시키고, 통합 검색은 그 뒤(20)로 민다.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tb_menu_info SET menu_ordr = 20, mdfcn_dt = CURRENT_TIMESTAMP
 WHERE menu_sn = 1000001 AND menu_ordr = 19;

