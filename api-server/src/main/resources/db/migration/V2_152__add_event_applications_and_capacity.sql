        ('APLY_STTS_CD', '신청상태코드', '코드C12'),
        ('EVNT_SN', '행사일련번호', '일련번호N19'),
        ('APLCNT_ID', '신청자아이디', '명V20'),
        ('APLY_DT', '신청일시', '연월일시분초D'),
        ('APLY_PRCS_DT', '신청처리일시', '연월일시분초D'),
        ('APLY_RTRCN_DT', '신청취소일시', '연월일시분초D'),
        ('PSCP_NOPE', '정원인원수', '수N10'),
        ('APLY_DDLN_YMD', '신청마감일자', '연월일C8')
    ) AS terms(eng_abbr, term_name, domain_name)
    LOOP
        IF (SELECT count(*) FROM meta_standard_terms t
             WHERE t.eng_abbr = expected.eng_abbr AND t.term_name = expected.term_name
               AND t.domain_name = expected.domain_name AND t.deprecated_yn = 'N') <> 1 THEN
            RAISE EXCEPTION 'V2_152: 표준 용어 % (% / %) 를 확인할 수 없습니다.',
                expected.eng_abbr, expected.term_name, expected.domain_name;
        END IF;
    END LOOP;
END $$;

