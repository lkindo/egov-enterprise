-- 관리 센터 > 콘텐츠 운영(9030000) 아래에 관리 화면 메뉴를 하나 더한다. 같은 분류의 다른 메뉴처럼 관리자 그룹에만 보이고,
-- 메뉴 표시(NAVIGATION) 배정은 권한 변경 이력에 같은 정책 버전으로 남긴다(V2_100 형식). 화면 진입은 CMS_ADMIN_READ 가 판정한다.
DO $cms_menu$
DECLARE
    catalog_version text;
    page_menu bigint;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM tb_menu_info WHERE menu_sn = 9030000) THEN
        RAISE EXCEPTION 'CMS menu parent (content operations 9030000) is missing';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_menu_info WHERE modern_route = '/admin/system/content-pages') THEN
        RAISE EXCEPTION 'CMS menu already exists';
    END IF;
    SELECT plcy_ver_no INTO STRICT catalog_version FROM tb_authrt_chg_hstry
     WHERE chg_artcl_nm = 'legacy_authorization_contract' AND chg_type_cd = 'UPDATE';

    INSERT INTO tb_menu_info(menu_nm, menu_ordr, menu_expln, up_menu_sn, modern_route, use_yn, del_yn,
        frst_rgtr_id, crt_dt, last_mdfr_id, mdfcn_dt)
    VALUES ('콘텐츠 페이지',
        (SELECT coalesce(max(menu_ordr), 0) + 1 FROM tb_menu_info WHERE up_menu_sn = 9030000),
        '안내 페이지 작성·게시와 업무 홈 소개', 9030000, '/admin/system/content-pages', 'Y', 'N',
        'SYSTEM', CURRENT_TIMESTAMP, 'SYSTEM', CURRENT_TIMESTAMP)
    RETURNING menu_sn INTO page_menu;

    WITH added AS (
        INSERT INTO tb_authrt_grnt_map(authrt_cd, authrt_type_cd, authrt_grnt_cd, frst_rgtr_id, crt_dt, last_mdfr_id, mdfcn_dt)
        SELECT a.authrt_cd, 'NAVIGATION', page_menu::text, 'SYSTEM', CURRENT_TIMESTAMP, 'SYSTEM', CURRENT_TIMESTAMP
          FROM tb_authrt_info a WHERE a.authrt_cd = 'ROLE_ADMIN'
        RETURNING authrt_cd, authrt_grnt_cd
    ) INSERT INTO tb_authrt_chg_hstry(dmnd_idntfr, plcy_ver_no, chg_trgt_type_cd, chg_type_cd, authrt_cd,
        authrt_type_cd, authrt_grnt_cd, chg_artcl_nm, chg_bfr_cn, chg_aftr_cn, chg_rsn, frst_rgtr_id, crt_dt)
    SELECT 'migration:2.137', catalog_version, 'GROUP_GRANT', 'ADD', authrt_cd, 'NAVIGATION', authrt_grnt_cd,
        'grant', NULL, authrt_grnt_cd, 'ADR-0039: 콘텐츠 페이지 관리 메뉴', 'SYSTEM', CURRENT_TIMESTAMP FROM added;
END $cms_menu$;
