CREATE TABLE tb_cms_conts (
    conts_sn bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sq_cms_conts_sn),
    conts_path_nm varchar(100) NOT NULL,
    conts_ttl varchar(256) NOT NULL,
    conts_expln varchar(4000),
    conts_doc_cn jsonb NOT NULL,
    conts_rvsn_sn bigint,
    kpng_yn varchar(1) NOT NULL DEFAULT 'N',
    version integer NOT NULL DEFAULT 0,
    frst_rgtr_id varchar(20),
    crt_dt timestamp without time zone NOT NULL,
    last_mdfr_id varchar(20),
    mdfcn_dt timestamp without time zone NOT NULL,
    CONSTRAINT pk_tb_cms_conts PRIMARY KEY (conts_sn),
    CONSTRAINT uk_tb_cms_conts_conts_path_nm UNIQUE (conts_path_nm),
    CONSTRAINT ck_tb_cms_conts_conts_path_nm CHECK (conts_path_nm ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_tb_cms_conts_conts_ttl CHECK (btrim(conts_ttl) <> ''),
    CONSTRAINT ck_tb_cms_conts_conts_doc_cn CHECK (jsonb_typeof(conts_doc_cn) = 'object'
        AND octet_length(conts_doc_cn::text) <= 1048576),
    CONSTRAINT ck_tb_cms_conts_kpng_yn CHECK (kpng_yn IN ('N', 'Y')),
    CONSTRAINT ck_tb_cms_conts_kpng_unpublished CHECK (kpng_yn = 'N' OR conts_rvsn_sn IS NULL),
    CONSTRAINT ck_tb_cms_conts_version CHECK (version >= 0)
);

CREATE TABLE tb_cms_conts_rvsn (
    conts_rvsn_sn bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sq_cms_conts_rvsn_sn),
    conts_sn bigint NOT NULL,
    conts_ttl varchar(256) NOT NULL,
    conts_expln varchar(4000),
    conts_doc_cn jsonb NOT NULL,
    rvsn_rsn varchar(4000),
    frst_rgtr_id varchar(20),
    crt_dt timestamp without time zone NOT NULL,
    CONSTRAINT pk_tb_cms_conts_rvsn PRIMARY KEY (conts_rvsn_sn),
    CONSTRAINT fk_tb_cms_conts_rvsn_tb_cms_conts FOREIGN KEY (conts_sn) REFERENCES tb_cms_conts (conts_sn),
    CONSTRAINT uk_tb_cms_conts_rvsn_conts_sn_conts_rvsn_sn UNIQUE (conts_sn, conts_rvsn_sn),
    CONSTRAINT ck_tb_cms_conts_rvsn_conts_ttl CHECK (btrim(conts_ttl) <> ''),
    CONSTRAINT ck_tb_cms_conts_rvsn_conts_doc_cn CHECK (jsonb_typeof(conts_doc_cn) = 'object'
        AND octet_length(conts_doc_cn::text) <= 1048576)
);

