-- 게시본은 고칠 수도 지울 수도 없다 — 리비전과 그 첨부 집합 모두. 새 게시는 새 행을 더한다.
CREATE FUNCTION fn_cms_rvsn_chg_prhb() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'CMS published revision is append-only: % on %', TG_OP, TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END $$;

COMMENT ON FUNCTION fn_cms_rvsn_chg_prhb() IS '콘텐츠 게시 리비전·리비전 첨부의 수정·삭제 금지 (ADR-0039)';

CREATE TRIGGER tr_tb_cms_conts_rvsn_chg_prhb
    BEFORE UPDATE OR DELETE ON tb_cms_conts_rvsn
    FOR EACH ROW EXECUTE FUNCTION fn_cms_rvsn_chg_prhb();

CREATE TRIGGER tr_tb_cms_conts_rvsn_file_chg_prhb
    BEFORE UPDATE OR DELETE ON tb_cms_conts_rvsn_file
    FOR EACH ROW EXECUTE FUNCTION fn_cms_rvsn_chg_prhb();

