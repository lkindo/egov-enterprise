-- V2_137: 콘텐츠 페이지(CMS) 1차 — 초안·불변 게시 리비전·페이지 소유 첨부·업무 홈 소개 지정(2026-10-22, ADR-0039).
-- 선택 기능 cms 가 소유하는 새 표 다섯 개다. 기존 표는 바꾸지 않는다(Expand 전용, 되돌리기는 기능 중지 — 표를 지우지 않는다).
-- 문서 정본은 jsonb 하나다(초안: tb_cms_conts, 게시본: tb_cms_conts_rvsn). 허용 구조는 서버 검증기 한 곳이 판정하고 DB 는
--   최상위가 객체인지와 크기 상한만 본다 — 문서를 해석하는 트리거를 두지 않는다(ADR-0039 결정 5).
-- 게시 리비전과 리비전 첨부 집합은 INSERT 만 받는다(트리거, V2_132 형식). 현재 게시 포인터는 같은 페이지의 리비전만 가리킨다
--   (복합 FK). 보관한 페이지는 게시 포인터가 비어 있어야 한다.
-- 첨부: 페이지가 쓰는 이미지는 기존 업로드 API 로 올린 첨부다. tb_cms_conts_file 이 첨부 하나(마스터·순서)를 페이지 하나에 묶고,
--   tb_file_detail 의 (atch_file_sn, atch_file_seq) 유니크를 가리키는 FK 로 일반 파일 삭제를 막는다(core 표는 그대로).
--   atch_file_seq 는 표준 도메인이 순서N10(numeric) 이지만 FK 대상 tb_file_detail.atch_file_seq 가 integer 라 같은 integer 로 둔다
--   (FK 는 같은 형이어야 한다 — GAP-STD-001 의 NUMERIC→integer 같은 종류 허용과 같은 처리).
-- 낙관적 잠금 컬럼은 DEC-OPS-378 의 기술 컬럼 예외(version integer)다. 감사 컬럼은 공통 감사 계약대로 로그인 ID 다.
-- 관리 화면 메뉴 한 행(관리 센터 > 콘텐츠 운영 > 콘텐츠 페이지)과 그 관리자 그룹 메뉴 표시 배정·이력을 함께 더한다.
-- H1: 새 용어 여섯·새 도메인 하나를 등록하고 쓰는 모든 용어·도메인을 아래 DO 블록이 다시 확인한다.
