-- 표준 단어는 이미 대표 단어로 등록돼 있다(V2_1).
DO $$
DECLARE
    expected RECORD;
BEGIN
    FOR expected IN SELECT * FROM (VALUES
        ('콘텐츠','CONTS'), ('경로','PATH'), ('명','NM'), ('문서','DOC'), ('내용','CN'), ('개정','RVSN'),
        ('일련번호','SN'), ('파일','FILE'), ('사이트','SITE'), ('설정','STNG'), ('코드','CD')
    ) AS words(word_name,eng_abbr)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM meta_standard_words w
                       WHERE w.word_name=expected.word_name AND w.eng_abbr=expected.eng_abbr
                         AND w.rprs_yn='Y') THEN
            RAISE EXCEPTION 'CMS standard word is missing or not representative: %',expected.eng_abbr;
        END IF;
    END LOOP;
END $$;

