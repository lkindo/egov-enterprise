-- V2_139: 게시판 운영 관리 A2(ADR-0040 결정 9·10). 게시판 마스터에 낙관적 잠금 버전을 두고, 운영 처리를 남기는 게시판 변경
-- 이력 표를 만든다(2026-10-23 사용자 일괄 승인, DEC-OPS-379).
--
-- 버전: 종전에는 두 관리자가 같은 게시판 설정을 열고 차례로 저장하면 늦은 저장이 앞 저장을 알림 없이 덮었다. 엔티티의
-- @Version 과 화면이 돌려보내는 읽은 버전으로 서버가 409(CONCURRENT_MODIFICATION)를 낸다. 형식은 V2_133 과 같은
-- `version integer NOT NULL DEFAULT 0` 과 음수 CHECK 다 — 표준 용어를 만들지 않는 기술 컬럼 예외(DEC-OPS-378)다.
--
-- 이력: 공통코드 변경 이력(V2_110)과 같은 용어·형태다. 설정 변경·사용 여부 변경·게시 기간 변경·고정과 해제를 값이 바뀐
-- 항목마다 한 행씩, 변경과 같은 트랜잭션에서 추가만 한다. 대상 유형은 게시판(BBS)·게시글(PST)이고, 게시글 행은 게시글
-- 번호가 있어야 한다. 게시판을 영구 삭제해도 이력이 남도록 외래 키를 두지 않는다. 변경 유형에는 뒤 배치(B1·B2)가 쓸
-- 게시 기간·고정 값을 미리 넣어 제약을 다시 바꾸지 않는다. 표 식별 번호(bbs_chg_hstry_sn)는 V2_110 처럼 표준 용어를
-- 등록하지 않는다(GAP-STD-001 등록 후보).
--
-- Expand 전용이다. 기존 행은 DEFAULT 로 0 이 되고(PostgreSQL 11+ 의 빠른 기본값 — 표를 다시 쓰지 않는다), 이 컬럼을 모르는
-- 이전 앱은 INSERT 에서 생략해도 기본값으로 채워진다. 새 표는 이전 앱이 읽거나 쓰지 않는다.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

ALTER TABLE tb_bbs_master ADD COLUMN version integer NOT NULL DEFAULT 0;
ALTER TABLE tb_bbs_master ADD CONSTRAINT ck_tb_bbs_master_version CHECK (version >= 0);
COMMENT ON COLUMN tb_bbs_master.version IS '버전 (낙관적 잠금, 저장할 때마다 오른다)';

CREATE TABLE tb_bbs_chg_hstry (
    bbs_chg_hstry_sn bigint GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME sq_bbs_chg_hstry_sn),
    chg_trgt_type_cd varchar(12) NOT NULL,
    chg_type_cd varchar(12) NOT NULL,
    bbs_id varchar(20) NOT NULL,
    pst_sn bigint,
    chg_artcl_nm varchar(100) NOT NULL,
    chg_bfr_cn varchar(4000),
    chg_aftr_cn varchar(4000),
    chg_user_idntfr varchar(20),
    frst_rgtr_id varchar(20) NOT NULL,
    crt_dt timestamp without time zone NOT NULL,
    CONSTRAINT pk_tb_bbs_chg_hstry PRIMARY KEY (bbs_chg_hstry_sn),
    CONSTRAINT ck_tb_bbs_chg_hstry_chg_trgt_type_cd
        CHECK (chg_trgt_type_cd IN ('BBS','PST')),
    CONSTRAINT ck_tb_bbs_chg_hstry_chg_type_cd
        CHECK (chg_type_cd IN ('SETTING','USE','PERIOD','PIN','UNPIN')),
    CONSTRAINT ck_tb_bbs_chg_hstry_target_shape CHECK (
        (chg_trgt_type_cd='BBS' AND pst_sn IS NULL)
        OR (chg_trgt_type_cd='PST' AND pst_sn IS NOT NULL)
    ),
    CONSTRAINT ck_tb_bbs_chg_hstry_change_value CHECK (
        chg_bfr_cn IS NOT NULL OR chg_aftr_cn IS NOT NULL
    )
);
CREATE INDEX ix_tb_bbs_chg_hstry_bbs_id ON tb_bbs_chg_hstry(bbs_id,crt_dt,bbs_chg_hstry_sn);

COMMENT ON TABLE tb_bbs_chg_hstry IS '게시판변경이력';
COMMENT ON COLUMN tb_bbs_chg_hstry.bbs_chg_hstry_sn IS '게시판변경이력일련번호';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_trgt_type_cd IS '변경대상유형코드 (BBS 게시판·PST 게시글)';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_type_cd IS '변경유형코드 (SETTING 설정·USE 사용 여부·PERIOD 게시 기간·PIN 고정·UNPIN 고정 해제)';
COMMENT ON COLUMN tb_bbs_chg_hstry.bbs_id IS '게시판ID';
COMMENT ON COLUMN tb_bbs_chg_hstry.pst_sn IS '게시글일련번호 (게시글 행만)';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_artcl_nm IS '변경항목명';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_bfr_cn IS '변경전내용';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_aftr_cn IS '변경후내용';
COMMENT ON COLUMN tb_bbs_chg_hstry.chg_user_idntfr IS '변경자 esntlId 감사 사본';
COMMENT ON COLUMN tb_bbs_chg_hstry.frst_rgtr_id IS '공통 감사 loginId';
COMMENT ON COLUMN tb_bbs_chg_hstry.crt_dt IS '생성일시';
