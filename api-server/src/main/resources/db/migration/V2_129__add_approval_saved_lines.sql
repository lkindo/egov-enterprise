-- V2_129: 비공식결재(결재) 나의 결재선(2026-10-16 결재 동선 개선 D2, DEC-OPS-328).
-- 기안자가 자주 쓰는 결재선에 이름을 붙여 두고 기안 화면에서 불러온다. 개인 결재선만 둔다 — 공용 결재선은 관리 화면과
--   권한 설계가 따로 필요해 범위 밖이다. 결재 표에 상태를 더하지 않고 별도 표 두 개를 둔다 — 대기함·알림·통계·결재선 제안의
--   질의는 결재 표(tb_ifml_atrz_*)만 읽으므로 저장한 결재선이 섞이지 않는다. 결재 표와 V2_122·V2_123 표는 바꾸지 않는다(Expand 전용).
-- 사람은 esntlId 다 — 결재선 주인(user_id)과 결재선의 결재자(상세 user_id). frst_rgtr_id·last_mdfr_id 는 공통 감사 계약대로
--   로그인 ID 다.
-- 보존: 만료 없음, 1인 20개(서비스가 사용자 행을 잠근 뒤 센다), 같은 사람의 결재선 이름은 겹치지 않는다(유니크 — 엔티티 미러).
--   사용자 행이 지워지면 그 사람의 결재선도 함께 지워진다(ON DELETE CASCADE — 본인만 읽는 개인 설정이라 고아로 남기지 않는다,
--   V2_122 선례). 관리자 열람 경로는 없다.
-- 결재선의 결재자(상세 user_id)에는 FK 를 두지 않는다(tb_ifml_atrz_dtl·tb_ifml_atrz_tmpr_strg_dtl 과 같다) — 남의 결재선에 든
--   사람을 지울 때 막히거나 남의 결재선이 조용히 바뀌지 않게 한다. 저장할 때와 불러올 때 모두 지금 자격(사용 중·결재 권한·본인 아님)을
--   서비스가 판정하고, 불러올 때 자격을 잃은 사람은 이름을 싣지 않고 빼서 그 수만 알린다.
-- H1: APLN_NM 명V200·ATRZ_SEQ 순서N10·ACRD_YN 여부C1·USER_ID 명V20 을 아래 DO 블록이 다시 확인한다. 새 용어는
--   IFML_ATRZ_INDV_APLN_SN 하나다(V2_122 의 IFML_ATRZ_TMPR_STRG_SN 과 같은 형식).
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

-- 표준 단어는 이미 등록돼 있다(V2_1). 새 복합 용어 하나만 등록한다(V2_122 형식).
DO $$
DECLARE
    expected RECORD;
BEGIN
    FOR expected IN SELECT * FROM (VALUES
        ('비공식','IFML'), ('결재','ATRZ'), ('개인','INDV'), ('결재선','APLN'), ('일련번호','SN')
    ) AS words(word_name,eng_abbr)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM meta_standard_words w
                       WHERE w.word_name=expected.word_name AND w.eng_abbr=expected.eng_abbr
                         AND w.rprs_yn='Y') THEN
            RAISE EXCEPTION 'Approval saved line standard word is missing or not representative: %',expected.eng_abbr;
        END IF;
    END LOOP;
END $$;

INSERT INTO meta_standard_terms (term_name, eng_abbr, description, domain_name)
VALUES ('비공식결재개인결재선일련번호', 'IFML_ATRZ_INDV_APLN_SN',
        '기안자가 이름을 붙여 저장해 둔 비공식 결재의 개인 결재선에 연속되게 매긴 번호', '일련번호N19')
ON CONFLICT (eng_abbr) DO NOTHING;

DO $$
DECLARE
    expected RECORD;
BEGIN
    FOR expected IN SELECT * FROM (VALUES
        ('IFML_ATRZ_INDV_APLN_SN','비공식결재개인결재선일련번호','일련번호N19'),
        ('APLN_NM','결재선명','명V200'),
        ('ATRZ_SEQ','결재순서','순서N10'), ('ACRD_YN','합의여부','여부C1'),
        ('USER_ID','사용자아이디','명V20'),
        ('FRST_RGTR_ID','최초등록자아이디','명V20'),
        ('LAST_MDFR_ID','최종수정자아이디','명V20'),
        ('CRT_DT','생성일시','연월일시분초D'),
        ('MDFCN_DT','수정일시','연월일시분초D')
    ) AS terms(eng_abbr,term_name,domain_name)
    LOOP
        IF (SELECT count(*) FROM meta_standard_terms t
            WHERE t.eng_abbr=expected.eng_abbr AND t.term_name=expected.term_name
              AND t.domain_name=expected.domain_name) <> 1 THEN
            RAISE EXCEPTION 'Approval saved line standard term conflict: %',expected.eng_abbr;
        END IF;
    END LOOP;
END $$;

CREATE TABLE tb_ifml_atrz_indv_apln (
    ifml_atrz_indv_apln_sn bigint GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME sq_ifml_atrz_indv_apln_sn),
    user_id varchar(20) NOT NULL,
    apln_nm varchar(200) NOT NULL,
    frst_rgtr_id varchar(20),
    crt_dt timestamp without time zone NOT NULL,
    last_mdfr_id varchar(20),
    mdfcn_dt timestamp without time zone NOT NULL,
    CONSTRAINT pk_tb_ifml_atrz_indv_apln PRIMARY KEY (ifml_atrz_indv_apln_sn),
    CONSTRAINT fk_tb_ifml_atrz_indv_apln_tb_user_info FOREIGN KEY (user_id)
        REFERENCES tb_user_info (esntl_id) ON DELETE CASCADE,
    CONSTRAINT uk_tb_ifml_atrz_indv_apln_user_id_apln_nm UNIQUE (user_id, apln_nm),
    CONSTRAINT ck_tb_ifml_atrz_indv_apln_apln_nm CHECK (btrim(apln_nm) <> '')
);

CREATE TABLE tb_ifml_atrz_indv_apln_dtl (
    ifml_atrz_indv_apln_sn bigint NOT NULL,
    atrz_seq numeric(10, 0) NOT NULL,
    user_id varchar(20) NOT NULL,
    acrd_yn varchar(1) NOT NULL DEFAULT 'N',
    frst_rgtr_id varchar(20),
    crt_dt timestamp without time zone NOT NULL,
    last_mdfr_id varchar(20),
    mdfcn_dt timestamp without time zone NOT NULL,
    CONSTRAINT pk_tb_ifml_atrz_indv_apln_dtl PRIMARY KEY (ifml_atrz_indv_apln_sn, atrz_seq, user_id),
    CONSTRAINT fk_tb_ifml_atrz_indv_apln_dtl_tb_ifml_atrz_indv_apln
        FOREIGN KEY (ifml_atrz_indv_apln_sn) REFERENCES tb_ifml_atrz_indv_apln (ifml_atrz_indv_apln_sn)
        ON DELETE CASCADE,
    CONSTRAINT ck_tb_ifml_atrz_indv_apln_dtl_atrz_seq CHECK (atrz_seq BETWEEN 1 AND 10),
    CONSTRAINT ck_tb_ifml_atrz_indv_apln_dtl_acrd_yn CHECK (acrd_yn IN ('N', 'Y'))
);

