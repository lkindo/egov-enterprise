UPDATE tb_popup_info popup
SET file_url = '/api/v1/files/' || parent.atch_file_sn
FROM tb_file_master parent
WHERE popup.file_url = '/api/v1/files/' || parent.atch_file_id
   OR popup.file_url = '/api/v1/files/download?fileId=' || parent.atch_file_id;

-- Contract 전에 누락이 없음을 증명한다. nullable 업무 참조는 기존 값이 있을 때만 새 값이 필수다.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM tb_file_master WHERE atch_file_sn IS NULL) THEN
        RAISE EXCEPTION 'tb_file_master.atch_file_sn backfill failed';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_file_detail WHERE atch_file_sn IS NULL) THEN
        RAISE EXCEPTION 'tb_file_detail.atch_file_sn relationship backfill failed';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_bbs_item WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_bnr_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_dept_task_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_diary_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_dta_use_stats WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_email_dsptch_manage WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_memo_rpt_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_note_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_rpt_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_rward_manage WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_schdl_info WHERE atch_file_id IS NOT NULL AND atch_file_sn IS NULL) THEN
        RAISE EXCEPTION 'attachment business relationship backfill failed';
    END IF;
    IF EXISTS (
        SELECT 1
        FROM tb_popup_info
        WHERE file_url LIKE '/api/v1/files/download?fileId=%'
           OR (file_url LIKE '/api/v1/files/FILE\_%' ESCAPE '\')
    ) THEN
        RAISE EXCEPTION 'tb_popup_info.file_url attachment backfill failed';
    END IF;
END $$;

