-- 파일 상세의 atch_file_seq는 마스터 안의 업무 순번이므로 그대로 보존한다.
-- 사용자 승인: 비운영 시스템의 기존 데이터 일괄 변환 + 이번 PK 현대화에 한한 DB 헌법 예외(2026-08-13).

-- 공공 표준사전의 ATCH_FILE_SN은 NUMERIC(10)으로 매핑돼 있으나, 프로젝트 자동 내부키 표준인
-- BIGINT(19)에 맞춰 프로젝트 확장 도메인으로 명시적으로 재매핑한다.
UPDATE meta_standard_terms
SET domain_name = '일련번호N19'
WHERE term_name = '첨부파일일련번호'
  AND eng_abbr = 'ATCH_FILE_SN';

DO $$
BEGIN
    IF (SELECT count(*) FROM meta_standard_terms
        WHERE term_name = '첨부파일일련번호'
          AND eng_abbr = 'ATCH_FILE_SN'
          AND domain_name = '일련번호N19') <> 1 THEN
        RAISE EXCEPTION 'standard term conflict: ATCH_FILE_SN must map to 일련번호N19';
    END IF;
END $$;

