INSERT INTO meta_standard_terms (term_name, eng_abbr, description, domain_name)
VALUES ('상위게시물일련번호', 'UP_PST_SN',
        '상위 게시물 내부 레코드에 연속되게 매긴 번호', '일련번호N22')
ON CONFLICT (eng_abbr) DO NOTHING;

DO $$
BEGIN
    IF (SELECT count(*) FROM meta_standard_terms
        WHERE term_name = '게시물일련번호'
          AND eng_abbr = 'PST_SN'
          AND domain_name = '일련번호N22') <> 1 THEN
        RAISE EXCEPTION 'standard term conflict: PST_SN must map to 일련번호N22';
    END IF;
    IF (SELECT count(*) FROM meta_standard_terms
        WHERE term_name = '상위게시물일련번호'
          AND eng_abbr = 'UP_PST_SN'
          AND domain_name = '일련번호N22') <> 1 THEN
        RAISE EXCEPTION 'standard term conflict: UP_PST_SN must map to 일련번호N22';
    END IF;
END $$;

ALTER TABLE tb_bbs_item
    ADD COLUMN pst_sn BIGINT GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME sq_pst_sn),
    ADD COLUMN up_pst_sn BIGINT;
ALTER TABLE tb_bbs_comment ADD COLUMN pst_sn BIGINT;
ALTER TABLE tb_bbs_scrap ADD COLUMN pst_sn BIGINT;
ALTER TABLE tb_dgstfn_info ADD COLUMN pst_sn BIGINT;
