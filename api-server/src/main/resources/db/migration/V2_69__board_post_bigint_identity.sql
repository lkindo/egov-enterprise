UPDATE tb_bbs_item child
SET up_pst_sn = parent.pst_sn
FROM tb_bbs_item parent
WHERE child.up_pst_id IS NOT NULL
  AND child.up_pst_id <> '0'
  AND child.up_pst_id = parent.pst_id;
UPDATE tb_bbs_comment child
SET pst_sn = parent.pst_sn
FROM tb_bbs_item parent
WHERE child.pst_id = parent.pst_id;
UPDATE tb_bbs_scrap child
SET pst_sn = parent.pst_sn
FROM tb_bbs_item parent
WHERE child.pst_id = parent.pst_id;
UPDATE tb_dgstfn_info child
SET pst_sn = parent.pst_sn
FROM tb_bbs_item parent
WHERE child.pst_id = parent.pst_id;
UPDATE tb_dta_use_stats child
SET pst_sn = parent.pst_sn
FROM tb_bbs_item parent
WHERE child.pst_id = parent.pst_id;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM tb_bbs_item WHERE pst_sn IS NULL) THEN
        RAISE EXCEPTION 'tb_bbs_item.pst_sn backfill failed';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_bbs_item
               WHERE up_pst_id IS NOT NULL AND up_pst_id <> '0' AND up_pst_sn IS NULL) THEN
        RAISE EXCEPTION 'tb_bbs_item.up_pst_sn relationship backfill failed';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_bbs_comment WHERE pst_id IS NOT NULL AND pst_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_bbs_scrap WHERE pst_id IS NOT NULL AND pst_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_dgstfn_info WHERE pst_sn IS NULL)
        OR EXISTS (SELECT 1 FROM tb_dta_use_stats WHERE pst_id IS NOT NULL AND pst_sn IS NULL) THEN
        RAISE EXCEPTION 'board post inbound relationship backfill failed';
    END IF;
END $$;

