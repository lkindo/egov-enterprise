        ('ROLE_SYSTEM','ROLE_ADMIN'),('ROLE_ADMIN','ROLE_USER'))
       OR (SELECT count(*) FROM tb_role_hierarchy) <> 2 THEN
        RAISE EXCEPTION 'Unreviewed legacy role hierarchy';
    END IF;
