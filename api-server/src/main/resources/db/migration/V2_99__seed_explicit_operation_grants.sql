        RAISE EXCEPTION 'Unreviewed legacy user group; no implicit default is allowed';
    END IF;
    IF EXISTS (SELECT 1 FROM tb_authrt_grnt_map WHERE authrt_type_cd='OPERATION') THEN
        RAISE EXCEPTION 'Operation grants already exist before the initial reviewed seed';
    END IF;
END $$;

